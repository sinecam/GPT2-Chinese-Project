def main() -> None:
    parser = argparse.ArgumentParser(description="Build small V4.4 identity and behavior boost JSONL.")
    parser.add_argument("--out", type=str, default="data/raw/V4.4_identity_boost.jsonl")
    parser.add_argument("--repeat", type=int, default=80)
    parser.add_argument("--seed", type=int, default=44)
    args = parser.parse_args()

    rows = []
    for _ in range(args.repeat):
        for instruction, output in IDENTITY_EXAMPLES:
            rows.append({"instruction": instruction, "input": "", "output": output})

    random.seed(args.seed)
    random.shuffle(rows)

    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")

    print(json.dumps({"output": str(out_path), "records": len(rows)}, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
